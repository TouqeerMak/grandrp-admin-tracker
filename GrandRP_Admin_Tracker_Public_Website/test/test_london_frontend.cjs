const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../public/app.js'), 'utf8');
const start = source.indexOf("const TZ=");
const prefixEnd = source.indexOf('function setNotice(');
const datesStart = source.indexOf('// Convert a wall-clock date');
const datesEnd = source.indexOf('function importCsv(');
assert(start !== -1 && prefixEnd > start && datesStart > prefixEnd && datesEnd > datesStart);
const functions = new Function(`${source.slice(start, prefixEnd)}\n${source.slice(datesStart, datesEnd)}\nreturn {TZ, fmtDate, dayKey, rangeFor, parseImportedDate};`)();
assert.equal(functions.TZ, 'Europe/London');
assert.equal(functions.dayKey(Date.parse('2026-06-30T23:30:00Z')), '2026-07-01');
assert.equal(functions.dayKey(Date.parse('2026-11-20T23:30:00Z')), '2026-11-20');
assert.match(functions.fmtDate(Date.parse('2026-07-01T12:00:00Z')), /1:00\s*pm/i);
assert.equal(functions.parseImportedDate('15/07/2026 12:00','Europe/London'), Date.parse('2026-07-15T11:00:00Z'));
assert.equal(functions.parseImportedDate('15/01/2026 12:00','Europe/London'), Date.parse('2026-01-15T12:00:00Z'));
assert.equal(functions.parseImportedDate('15/07/2026 12:00','Australia/Perth'), Date.parse('2026-07-15T04:00:00Z'));
assert.equal(functions.parseImportedDate('15 Jul 2026, 12:00 pm','Europe/London'), Date.parse('2026-07-15T11:00:00Z'));
assert.equal(functions.parseImportedDate('2026-10-25T02:10:00.000Z'), Date.parse('2026-10-25T02:10:00.000Z'));
assert.equal(functions.rangeFor('custom','2026-07-01','2026-07-10').timezone, 'Europe/London');
console.log('Frontend timezone and CSV conversion tests passed.');
